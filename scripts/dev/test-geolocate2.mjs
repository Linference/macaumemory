import puppeteer from "puppeteer-core";
const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ["--no-sandbox","--disable-dev-shm-usage","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"], defaultViewport: { width: 1300, height: 820 } });
const ctx = browser.defaultBrowserContext();
await ctx.overridePermissions("http://127.0.0.1:4173", ["geolocation"]);
const page = await browser.newPage();
await page.setGeolocation({ latitude: 22.18615, longitude: 113.53133, accuracy: 20 });
await page.goto("http://127.0.0.1:4173/", { waitUntil: "domcontentloaded", timeout: 120000 });
await page.waitForFunction(() => document.querySelector("#boot")?.classList.contains("gone"), { timeout: 90000, polling: 400 });
await wait(4500);
const st = () => page.evaluate(() => ({ on: document.querySelector("#btn-locate").classList.contains("on"), following: document.querySelector("#btn-locate").classList.contains("following"), gps: document.querySelector(".gps").style.display !== "none", title: document.querySelector("#btn-locate").title }));
await page.click("#btn-locate"); await wait(4500); console.log("1 定位  →", JSON.stringify(await st()));
await page.click("#btn-locate"); await wait(1500); console.log("2 跟隨  →", JSON.stringify(await st()));
await page.setGeolocation({ latitude: 22.19746, longitude: 113.54084, accuracy: 25 }); await wait(5000);
console.log("   移動後 →", await page.evaluate(() => window.__map.getCenter().toArray().map((v) => +v.toFixed(4))));
await page.click("#btn-locate"); await wait(1500); console.log("3 停止  →", JSON.stringify(await st()));
await page.screenshot({ path: "preview/22-個人定位.png" });
await browser.close();
