#!/usr/bin/env bash
# 即夢生成 6 張電影感底景（16:9 4K，每張 4 積分）。用途：立意／意義／政策關聯／創新／收尾章節的視覺底景。
# 畫面為 AI 意象，不作為真實地點紀錄；片中會標示「AI 意象」。
set -u
cd "$(dirname "$0")/../public/gen"
gen() {
  local name="$1" prompt="$2"
  [ -f "$name.png" ] && { echo "skip $name"; return; }
  local out id
  out=$(dreamina text2image --resolution_type=4k --ratio=16:9 --generate_num=1 --poll=240 --prompt="$prompt" 2>&1)
  id=$(echo "$out" | grep -o '"submit_id": *"[^"]*"' | head -1 | sed 's/.*"\([^"]*\)"$/\1/')
  echo "$name submit_id=$id status=$(echo "$out" | grep -o '"gen_status": *"[^"]*"' | head -1)"
  [ -n "$id" ] || { echo "$out" | tail -5; return; }
  dreamina query_result --submit_id="$id" --download_dir=. >/dev/null 2>&1
  local f; f=$(ls -t "${id}"_image_1.* 2>/dev/null | head -1)
  [ -n "$f" ] && mv "$f" "$name.png" && echo "  → $name.png"
}

